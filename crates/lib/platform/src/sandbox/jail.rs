//! The production sandbox: one FreeBSD jail per task.
//!
//! Each jail gets a per-task `jail.conf` and `fstab` written next to its spec,
//! and is created and removed with `jail -f <conf> -c|-r <name>`. That way
//! jail(8) owns the whole mount lifecycle (nullfs for the read-only base
//! system and any granted paths, devfs with the restrictive jail ruleset), and
//! an operator can inspect or tear down any jail by hand with the same files.
//!
//! What the jail denies, for PA-1:
//! - files: only the read-only base system, the agent binaries, its private
//!   `/work` and `/tmp`, and paths the task explicitly mounts;
//! - network: `ip4 = disable` and `ip6 = disable` (no egress at all until
//!   per-jail pf rules land with the egress-control work);
//! - processes: jailed processes see and signal only their own jail;
//! - privilege: `securelevel = 3`, no mounts, no raw sockets, no child jails.
//!
//! And so the person comes first, the agent starts below their CPU priority
//! (`nice`) and the jail's rctl(8) limits ([`ResourceLimits`]) are added by
//! the jail's own `exec.prestart` and removed by its `exec.poststop`, so
//! they exist exactly as long as the jail does, however it is removed.

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process::Command;

use serde::{Deserialize, Serialize};

use super::{ProcessSpec, ResourceLimits, Sandbox, SandboxSpec, check_name, create_layout};
use crate::{PlatformError, Result, cmd};

/// Name prefix for every jail the daemon creates; stale-jail cleanup only
/// ever touches names with this prefix.
pub const JAIL_PREFIX: &str = "glass-";

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct JailConfig {
    /// Host directories mounted read-only at the same path in every jail.
    /// Enough of the base system for dynamically linked programs to run.
    pub base_mounts: Vec<PathBuf>,
    /// Where per-jail `.conf`, `.fstab` and `.spec.json` files live, beside
    /// the jails' roots: on a disk that keeps them across a restart of the
    /// computer, so [`Sandbox::cleanup_stale`] finds every sandbox a power
    /// cut left (ADR 0053). Not `/var/run`, which the boot empties.
    pub state_dir: PathBuf,
    /// devfs ruleset for `/dev`. 4 is the stock `devfsrules_jail`.
    pub devfs_ruleset: u32,
    /// What every task may use; see [`ResourceLimits`].
    #[serde(default)]
    pub limits: ResourceLimits,
}

impl Default for JailConfig {
    fn default() -> Self {
        Self {
            base_mounts: [
                "/bin",
                "/lib",
                "/libexec",
                "/usr/bin",
                "/usr/lib",
                "/usr/libexec",
                "/usr/share",
            ]
            .into_iter()
            .map(PathBuf::from)
            .collect(),
            state_dir: PathBuf::from("/var/db/glasshouse/sandboxes"),
            devfs_ruleset: 4,
            limits: ResourceLimits::default(),
        }
    }
}

#[derive(Debug)]
pub struct JailSandbox {
    config: JailConfig,
}

impl JailSandbox {
    pub fn new(config: JailConfig) -> Self {
        Self { config }
    }

    fn file(&self, spec_name: &str, ext: &str) -> PathBuf {
        self.config.state_dir.join(format!("{spec_name}.{ext}"))
    }

    /// The fstab jail(8) mounts before creating the jail and unmounts after
    /// removing it.
    pub fn render_fstab(&self, spec: &SandboxSpec) -> Result<String> {
        let mut lines = Vec::new();
        for base in &self.config.base_mounts {
            lines.push(fstab_line(base, &spec.root.join(strip_root(base)?), false)?);
        }
        for mount in &spec.mounts {
            lines.push(fstab_line(
                &mount.source,
                &spec.root.join(strip_root(&mount.target)?),
                mount.writable,
            )?);
        }
        Ok(lines.join("\n") + "\n")
    }

    pub fn render_conf(&self, spec: &SandboxSpec) -> String {
        // Names are letters, digits and dashes (check_name) and amounts are
        // numbers, so nothing here needs quoting for the shell jail(8) uses.
        let rules = self.config.limits.rctl_rules(&spec.name);
        let limits = if rules.is_empty() {
            String::new()
        } else {
            format!(
                "\texec.prestart = \"/usr/bin/rctl -a {rules}\";\n\
                 \texec.poststop = \"/usr/bin/rctl -r jail:{name}\";\n",
                rules = rules.join(" "),
                name = spec.name,
            )
        };
        format!(
            "# Generated by glassd for one agent task. Removed when the task ends.\n\
             {name} {{\n\
             \tpath = \"{root}\";\n\
             \thost.hostname = \"{name}\";\n\
             \tpersist;\n\
             \tip4 = disable;\n\
             \tip6 = disable;\n\
             \tmount.devfs;\n\
             \tdevfs_ruleset = {ruleset};\n\
             \tmount.fstab = \"{fstab}\";\n\
             \tenforce_statfs = 2;\n\
             \tchildren.max = 0;\n\
             \tsecurelevel = 3;\n\
             \tallow.raw_sockets = 0;\n\
             \tallow.mount = 0;\n\
             \tallow.chflags = 0;\n\
             \tallow.set_hostname = 0;\n\
             \tallow.sysvipc = 0;\n\
             {limits}\
             }}\n",
            name = spec.name,
            root = spec.root.display(),
            ruleset = self.config.devfs_ruleset,
            fstab = self.file(&spec.name, "fstab").display(),
        )
    }

    fn write_identity(&self, spec: &SandboxSpec) -> Result<()> {
        let etc = spec.root.join("etc");
        let write = |name: &str, text: String, mode: u32| -> Result<()> {
            let path = etc.join(name);
            fs::write(&path, text)
                .map_err(|e| PlatformError::io(format!("writing {}", path.display()), e))?;
            fs::set_permissions(&path, fs::Permissions::from_mode(mode))
                .map_err(|e| PlatformError::io(format!("chmod {}", path.display()), e))
        };
        write(
            "master.passwd",
            format!(
                "root:*:0:0::0:0:Charlie &:/root:/usr/sbin/nologin\n\
                 {user}:*:{uid}:{gid}::0:0:Glasshouse agent:/work:/usr/sbin/nologin\n",
                user = spec.user,
                uid = spec.uid,
                gid = spec.gid,
            ),
            0o600,
        )?;
        write(
            "group",
            format!(
                "wheel:*:0:root\n{user}:*:{gid}:\n",
                user = spec.user,
                gid = spec.gid
            ),
            0o644,
        )?;
        // Builds passwd, pwd.db and spwd.db so name lookups work inside.
        let master = etc.join("master.passwd");
        if let Err(e) = cmd::run(
            "pwd_mkdb",
            &[
                "-d",
                &etc.to_string_lossy(),
                "-p",
                &master.to_string_lossy(),
            ],
        ) {
            tracing::warn!(error = %e, "pwd_mkdb failed; name lookups inside the jail will not work");
        }
        Ok(())
    }

    /// Roots in the state folder with no spec beside them, other than
    /// `done`'s: made before their spec was written first, or their spec
    /// lost with /var/run (before ADR 0053). One whose spec is there but
    /// unreadable stays for an operator, as `cleanup_stale` leaves it.
    fn orphans(&self, entries: &[fs::DirEntry], done: &[String]) -> Vec<(String, PathBuf)> {
        entries
            .iter()
            .filter(|entry| entry.file_type().is_ok_and(|t| t.is_dir()))
            .filter_map(|entry| {
                let name = entry.file_name().to_str()?.to_owned();
                let orphan = name.starts_with(JAIL_PREFIX)
                    && check_name(&name).is_ok()
                    && !done.contains(&name)
                    && !self.file(&name, "spec.json").exists();
                orphan.then(|| (name, entry.path()))
            })
            .collect()
    }

    fn jail_exists(name: &str) -> bool {
        cmd::run("jls", &["-j", name, "jid"]).is_ok()
    }

    /// Mount points at or under `root`, deepest first.
    fn mounts_under(root: &Path) -> Result<Vec<PathBuf>> {
        let table = cmd::run("mount", &["-p"])?;
        let mut found: Vec<PathBuf> = table
            .lines()
            .filter_map(|line| line.split_whitespace().nth(1))
            .map(|field| PathBuf::from(field.replace("\\040", " ")))
            .filter(|mp| mp.starts_with(root))
            .collect();
        found.sort_by_key(|p| std::cmp::Reverse(p.components().count()));
        Ok(found)
    }
}

impl Sandbox for JailSandbox {
    fn kind(&self) -> &'static str {
        "jail"
    }

    fn is_security_boundary(&self) -> bool {
        true
    }

    fn create(&self, spec: &SandboxSpec) -> Result<()> {
        check_name(&spec.name)?;
        if !spec.name.starts_with(JAIL_PREFIX) {
            return Err(PlatformError::Unsafe(format!(
                "jail name must start with {JAIL_PREFIX}"
            )));
        }
        if spec.root.exists() {
            return Err(PlatformError::Unsafe(format!(
                "sandbox root {} already exists; refusing to reuse it",
                spec.root.display()
            )));
        }
        fs::create_dir_all(&self.config.state_dir)
            .map_err(|e| PlatformError::io("creating jail state dir", e))?;
        let fstab = self.render_fstab(spec)?;
        let write = |ext: &str, text: &str| {
            let path = self.file(&spec.name, ext);
            fs::write(&path, text)
                .map_err(|e| PlatformError::io(format!("writing {}", path.display()), e))
        };
        // The spec first, before anything it names exists: whenever glassd
        // stops, cleanup_stale finds everything made (ADR 0053).
        write("spec.json", &serde_json_string(spec)?)?;

        create_layout(spec)?;
        for base in &self.config.base_mounts {
            let mount_point = spec.root.join(strip_root(base)?);
            fs::create_dir_all(&mount_point)
                .map_err(|e| PlatformError::io(format!("creating {}", mount_point.display()), e))?;
        }
        for mount in &spec.mounts {
            let mount_point = spec.root.join(strip_root(&mount.target)?);
            fs::create_dir_all(&mount_point)
                .map_err(|e| PlatformError::io(format!("creating {}", mount_point.display()), e))?;
        }
        fs::create_dir_all(spec.root.join("dev"))
            .map_err(|e| PlatformError::io("creating dev", e))?;
        self.write_identity(spec)?;
        write("fstab", &fstab)?;
        write("conf", &self.render_conf(spec))?;

        let conf = self.file(&spec.name, "conf");
        if let Err(e) = cmd::run("jail", &["-f", &conf.to_string_lossy(), "-c", &spec.name]) {
            let _ = self.destroy(spec);
            return Err(e);
        }
        Ok(())
    }

    fn command(&self, spec: &SandboxSpec, process: &ProcessSpec) -> Command {
        // nice(1) runs jexec at the lower priority and the agent inherits
        // it; as an unprivileged user it can never raise it back.
        let mut command = match self.config.limits.nice {
            0 => Command::new("/usr/sbin/jexec"),
            n => {
                let mut nice = Command::new("/usr/bin/nice");
                nice.arg("-n").arg(n.to_string()).arg("/usr/sbin/jexec");
                nice
            }
        };
        command
            .arg("-u")
            .arg(&spec.user)
            .arg(&spec.name)
            .arg(&process.program)
            .args(&process.args)
            .env_clear()
            .envs(process.env.iter().map(|(k, v)| (k, v)));
        command
    }

    fn destroy(&self, spec: &SandboxSpec) -> Result<()> {
        check_name(&spec.name)?;
        let conf = self.file(&spec.name, "conf");
        let existed = Self::jail_exists(&spec.name);
        if existed {
            if conf.exists() {
                cmd::run("jail", &["-f", &conf.to_string_lossy(), "-r", &spec.name])?;
            } else {
                cmd::run("jail", &["-r", &spec.name])?;
            }
        }
        if (!existed || !conf.exists()) && !self.config.limits.rctl_rules(&spec.name).is_empty() {
            // No exec.poststop ran (a start that failed half way, or a jail
            // removed without its conf): remove any limits left behind.
            let _ = cmd::run("rctl", &["-r", &format!("jail:{}", spec.name)]);
        }

        // jail(8) unmounts what it mounted, but never delete a root that
        // still has anything mounted beneath it: removing it would recurse
        // into the mounted directories.
        for mount_point in Self::mounts_under(&spec.root)? {
            tracing::warn!(mount = %mount_point.display(), "unmounting leftover jail mount");
            let _ = cmd::run("umount", &["-f", &mount_point.to_string_lossy()]);
        }
        let leftover = Self::mounts_under(&spec.root)?;
        if !leftover.is_empty() {
            return Err(PlatformError::Unsafe(format!(
                "{} still has mounts ({}); not deleting it",
                spec.root.display(),
                leftover
                    .iter()
                    .map(|p| p.display().to_string())
                    .collect::<Vec<_>>()
                    .join(", ")
            )));
        }

        if spec.root.exists() {
            fs::remove_dir_all(&spec.root)
                .map_err(|e| PlatformError::io(format!("removing {}", spec.root.display()), e))?;
        }
        for ext in ["conf", "fstab", "spec.json"] {
            let _ = fs::remove_file(self.file(&spec.name, ext));
        }
        Ok(())
    }

    fn agent_path(&self, _spec: &SandboxSpec, inside: &Path) -> PathBuf {
        inside.to_path_buf()
    }

    fn cleanup_stale(&self) -> Result<Vec<String>> {
        let mut cleaned = Vec::new();
        let Ok(entries) = fs::read_dir(&self.config.state_dir) else {
            return Ok(cleaned);
        };
        let entries: Vec<fs::DirEntry> = entries.flatten().collect();
        for entry in &entries {
            let path = entry.path();
            let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
                continue;
            };
            let Some(jail_name) = name.strip_suffix(".spec.json") else {
                continue;
            };
            if !jail_name.starts_with(JAIL_PREFIX) {
                continue;
            }
            let spec: SandboxSpec = match fs::read_to_string(&path)
                .ok()
                .and_then(|text| serde_json_parse(&text))
            {
                Some(spec) => spec,
                None => {
                    tracing::warn!(file = %path.display(), "unreadable jail spec; leaving it for an operator");
                    continue;
                }
            };
            self.destroy(&spec)?;
            cleaned.push(spec.name);
        }
        for (name, root) in self.orphans(&entries, &cleaned) {
            self.destroy(&SandboxSpec {
                name: name.clone(),
                root,
                mounts: Vec::new(),
                user: String::new(),
                uid: 0,
                gid: 0,
                computer: None,
            })?;
            cleaned.push(name);
        }
        Ok(cleaned)
    }
}

fn strip_root(path: &Path) -> Result<&Path> {
    path.strip_prefix("/")
        .map_err(|_| PlatformError::Unsafe(format!("{} must be absolute", path.display())))
}

fn fstab_line(source: &Path, target: &Path, writable: bool) -> Result<String> {
    for p in [source, target] {
        let text = p.to_string_lossy();
        if text.chars().any(char::is_whitespace) || text.contains('#') {
            return Err(PlatformError::Unsupported(format!(
                "mounting paths with whitespace or '#' ({text})"
            )));
        }
    }
    let mode = if writable { "rw" } else { "ro" };
    Ok(format!(
        "{} {} nullfs {mode} 0 0",
        source.display(),
        target.display()
    ))
}

fn serde_json_string(spec: &SandboxSpec) -> Result<String> {
    serde_json::to_string_pretty(spec)
        .map_err(|e| PlatformError::io("encoding spec", std::io::Error::other(e)))
}

fn serde_json_parse(text: &str) -> Option<SandboxSpec> {
    serde_json::from_str(text).ok()
}

impl super::ToolRunner for JailSandbox {
    fn run_tool(&self, run: &super::ToolRun) -> Result<super::ToolOutput> {
        super::tool::run_jailed(run, &self.config.limits)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::sandbox::Mount;

    fn spec() -> SandboxSpec {
        SandboxSpec {
            name: "glass-0193ab12".into(),
            root: "/var/db/glasshouse/jails/glass-0193ab12".into(),
            mounts: vec![Mount {
                source: "/home/demo/Invoices".into(),
                target: "/data/Invoices".into(),
                writable: false,
            }],
            user: "demo".into(),
            uid: 1001,
            gid: 1001,
            computer: None,
        }
    }

    #[test]
    fn pa2_a_root_left_without_its_spec_is_found_at_the_next_start() {
        let dir = tempfile::tempdir().unwrap();
        let jails = JailSandbox::new(JailConfig {
            state_dir: dir.path().to_owned(),
            ..JailConfig::default()
        });
        for d in [
            "glass-0193ab12",
            "glass-0193ab13",
            "glass-0193ab14",
            "other",
        ] {
            fs::create_dir(dir.path().join(d)).unwrap();
        }
        // One with its spec, one with a spec nobody can read: not orphans.
        fs::write(dir.path().join("glass-0193ab13.spec.json"), "{}").unwrap();
        fs::write(dir.path().join("glass-0193ab14.spec.json"), "not json").unwrap();
        fs::write(dir.path().join("glass-0193ab15"), "a file").unwrap();
        let entries: Vec<fs::DirEntry> = fs::read_dir(dir.path()).unwrap().flatten().collect();
        let found: Vec<String> = jails
            .orphans(&entries, &[])
            .into_iter()
            .map(|(name, root)| {
                assert_eq!(root, dir.path().join(&name));
                name
            })
            .collect();
        assert_eq!(found, ["glass-0193ab12"]);
        assert!(jails.orphans(&entries, &found).is_empty());
    }

    #[test]
    fn fstab_mounts_base_read_only_then_grants() {
        let jail = JailSandbox::new(JailConfig {
            base_mounts: vec!["/bin".into()],
            ..Default::default()
        });
        let fstab = jail.render_fstab(&spec()).unwrap();
        assert_eq!(
            fstab,
            "/bin /var/db/glasshouse/jails/glass-0193ab12/bin nullfs ro 0 0\n\
             /home/demo/Invoices /var/db/glasshouse/jails/glass-0193ab12/data/Invoices nullfs ro 0 0\n"
        );
    }

    #[test]
    fn conf_disables_network_and_privilege() {
        let conf = JailSandbox::new(JailConfig::default()).render_conf(&spec());
        for needle in [
            "glass-0193ab12 {",
            "ip4 = disable;",
            "ip6 = disable;",
            "securelevel = 3;",
            "children.max = 0;",
            "allow.raw_sockets = 0;",
            "devfs_ruleset = 4;",
            "mount.fstab = \"/var/db/glasshouse/sandboxes/glass-0193ab12.fstab\";",
        ] {
            assert!(conf.contains(needle), "missing {needle:?} in\n{conf}");
        }
    }

    fn limited() -> JailSandbox {
        JailSandbox::new(JailConfig {
            limits: ResourceLimits {
                nice: 10,
                cpu_percent: 100,
                max_processes: 256,
                ..ResourceLimits::default()
            },
            ..JailConfig::default()
        })
    }

    #[test]
    fn limits_live_and_die_with_the_jail() {
        // PA-2: the jail's own prestart adds them, its poststop removes them.
        let conf = limited().render_conf(&spec());
        assert!(
            conf.contains(
                "exec.prestart = \"/usr/bin/rctl -a jail:glass-0193ab12:pcpu:deny=100 \
                 jail:glass-0193ab12:maxproc:deny=256\";"
            ),
            "{conf}"
        );
        assert!(
            conf.contains("exec.poststop = \"/usr/bin/rctl -r jail:glass-0193ab12\";"),
            "{conf}"
        );
        assert!(conf.trim_end().ends_with('}'));
        let unlimited = JailSandbox::new(JailConfig::default()).render_conf(&spec());
        assert!(!unlimited.contains("rctl"), "{unlimited}");
    }

    #[test]
    fn agents_start_below_the_persons_priority() {
        let process = ProcessSpec {
            program: "/usr/local/libexec/glasshouse/glass-probe".into(),
            args: Vec::new(),
            env: Vec::new(),
        };
        let command = limited().command(&spec(), &process);
        assert_eq!(command.get_program(), "/usr/bin/nice");
        let args: Vec<_> = command.get_args().map(|a| a.to_string_lossy()).collect();
        assert_eq!(
            args[..6],
            [
                "-n",
                "10",
                "/usr/sbin/jexec",
                "-u",
                "demo",
                "glass-0193ab12"
            ]
        );
        let plain = JailSandbox::new(JailConfig::default()).command(&spec(), &process);
        assert_eq!(plain.get_program(), "/usr/sbin/jexec");
    }

    #[test]
    fn whitespace_paths_are_refused_not_mangled() {
        let mut s = spec();
        s.mounts[0].source = "/home/demo/My Invoices".into();
        let jail = JailSandbox::new(JailConfig::default());
        assert!(matches!(
            jail.render_fstab(&s),
            Err(PlatformError::Unsupported(_))
        ));
    }
}
